CREATE OR REPLACE FUNCTION public.initialize_authoritative_match_v2(
  p_game_id UUID,
  p_canonical_state JSONB,
  p_player_a_projection JSONB,
  p_player_b_projection JSONB,
  p_started_at TIMESTAMPTZ,
  p_ends_at TIMESTAMPTZ,
  p_schema_version INTEGER DEFAULT 1,
  p_protocol_version INTEGER DEFAULT 2,
  p_ruleset_version INTEGER DEFAULT 1
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_player_a_id UUID;
  v_player_b_id UUID;
BEGIN
  IF COALESCE(jsonb_typeof(p_canonical_state), 'null') <> 'object'
    OR COALESCE(jsonb_typeof(p_player_a_projection), 'null') <> 'object'
    OR COALESCE(jsonb_typeof(p_player_b_projection), 'null') <> 'object' THEN
    RAISE EXCEPTION 'State and projections must be JSON objects';
  END IF;

  IF COALESCE((p_canonical_state ->> 'revision')::BIGINT, -1) <> 0
    OR COALESCE((p_player_a_projection ->> 'revision')::BIGINT, -1) <> 0
    OR COALESCE((p_player_b_projection ->> 'revision')::BIGINT, -1) <> 0 THEN
    RAISE EXCEPTION 'Initial state and projections must use revision zero';
  END IF;

  IF p_ends_at IS NOT NULL AND p_started_at IS NOT NULL AND p_ends_at <= p_started_at THEN
    RAISE EXCEPTION 'Match deadline must be later than its start time';
  END IF;

  SELECT COALESCE(player_a_id, host_id), player_b_id
  INTO v_player_a_id, v_player_b_id
  FROM public.games
  WHERE id = p_game_id;

  IF v_player_a_id IS NULL OR v_player_b_id IS NULL THEN
    RAISE EXCEPTION 'Ranked match requires two assigned players';
  END IF;

  INSERT INTO public.authoritative_matches (
    game_id,
    schema_version,
    protocol_version,
    ruleset_version,
    revision,
    status,
    canonical_state,
    started_at,
    ends_at
  ) VALUES (
    p_game_id,
    p_schema_version,
    p_protocol_version,
    p_ruleset_version,
    0,
    COALESCE(p_canonical_state #>> '{match,status}', 'setup'),
    p_canonical_state,
    p_started_at,
    p_ends_at
  );

  INSERT INTO public.match_projections (
    game_id, viewer_id, viewer_role, revision, projection
  ) VALUES
    (p_game_id, v_player_a_id, 'playerA', 0, p_player_a_projection),
    (p_game_id, v_player_b_id, 'playerB', 0, p_player_b_projection);

  INSERT INTO public.match_outbox (game_id, revision, viewer_id, payload)
  VALUES
    (p_game_id, 0, v_player_a_id, p_player_a_projection),
    (p_game_id, 0, v_player_b_id, p_player_b_projection);
END;
$$;

CREATE OR REPLACE FUNCTION public.begin_authoritative_match_command_v2(
  p_game_id UUID,
  p_command_id UUID,
  p_actor_id UUID,
  p_expected_revision BIGINT,
  p_command_type TEXT,
  p_payload JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_match public.authoritative_matches%ROWTYPE;
  v_existing public.match_commands%ROWTYPE;
  v_is_participant BOOLEAN;
  v_error_code TEXT;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM public.games
    WHERE id = p_game_id
      AND p_actor_id IN (COALESCE(player_a_id, host_id), player_b_id)
  ) INTO v_is_participant;

  IF NOT v_is_participant THEN
    RETURN jsonb_build_object('status', 'rejected', 'errorCode', 'unauthorized_actor');
  END IF;

  SELECT * INTO v_match
  FROM public.authoritative_matches
  WHERE game_id = p_game_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'rejected', 'errorCode', 'match_not_found');
  END IF;

  -- The match row lock serializes duplicate command IDs before this second
  -- lookup, avoiding a race between the idempotency check and ledger insert.
  SELECT * INTO v_existing
  FROM public.match_commands
  WHERE game_id = p_game_id AND command_id = p_command_id;

  IF FOUND THEN
    IF v_existing.actor_id <> p_actor_id
      OR v_existing.expected_revision IS DISTINCT FROM p_expected_revision
      OR v_existing.command_type IS DISTINCT FROM p_command_type
      OR v_existing.payload IS DISTINCT FROM COALESCE(p_payload, '{}'::JSONB) THEN
      RETURN jsonb_build_object('status', 'rejected', 'errorCode', 'command_id_conflict');
    END IF;

    RETURN jsonb_build_object(
      'status', v_existing.status,
      'revision', v_existing.committed_revision,
      'result', v_existing.result,
      'errorCode', v_existing.error_code
    );
  END IF;

  IF p_expected_revision IS NULL OR p_expected_revision < 0 THEN
    v_error_code := 'invalid_revision';
  ELSIF p_command_type IS NULL
    OR p_command_type NOT IN ('place_piece', 'respond_to_check', 'mark_piece', 'resolve_nexus') THEN
    RETURN jsonb_build_object('status', 'rejected', 'errorCode', 'invalid_command_type');
  ELSIF jsonb_typeof(COALESCE(p_payload, '{}'::JSONB)) <> 'object' THEN
    v_error_code := 'invalid_payload';
  ELSIF v_match.status <> 'active' THEN
    v_error_code := 'match_not_active';
  ELSIF v_match.ends_at IS NOT NULL AND clock_timestamp() >= v_match.ends_at THEN
    v_error_code := 'deadline_expired';
  ELSIF v_match.revision <> p_expected_revision THEN
    v_error_code := 'stale_revision';
  END IF;

  INSERT INTO public.match_commands (
    game_id,
    command_id,
    actor_id,
    expected_revision,
    command_type,
    payload,
    status,
    error_code,
    completed_at
  ) VALUES (
    p_game_id,
    p_command_id,
    p_actor_id,
    GREATEST(COALESCE(p_expected_revision, 0), 0),
    p_command_type,
    COALESCE(p_payload, '{}'::JSONB),
    CASE WHEN v_error_code IS NULL THEN 'pending' ELSE 'rejected' END,
    v_error_code,
    CASE WHEN v_error_code IS NULL THEN NULL ELSE NOW() END
  );

  IF v_error_code IS NOT NULL THEN
    RETURN jsonb_build_object(
      'status', 'rejected',
      'errorCode', v_error_code,
      'currentRevision', v_match.revision
    );
  END IF;

  RETURN jsonb_build_object(
    'status', 'pending',
    'revision', v_match.revision,
    'schemaVersion', v_match.schema_version,
    'protocolVersion', v_match.protocol_version,
    'rulesetVersion', v_match.ruleset_version,
    'canonicalState', v_match.canonical_state,
    'endsAt', v_match.ends_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.commit_authoritative_match_command_v2(
  p_game_id UUID,
  p_command_id UUID,
  p_actor_id UUID,
  p_expected_revision BIGINT,
  p_new_canonical_state JSONB,
  p_player_a_projection JSONB,
  p_player_b_projection JSONB,
  p_result JSONB DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_match public.authoritative_matches%ROWTYPE;
  v_command public.match_commands%ROWTYPE;
  v_player_a_id UUID;
  v_player_b_id UUID;
  v_next_revision BIGINT;
  v_actor_projection JSONB;
  v_command_result JSONB;
  v_next_status TEXT;
BEGIN
  SELECT * INTO v_match
  FROM public.authoritative_matches
  WHERE game_id = p_game_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'rejected', 'errorCode', 'match_not_found');
  END IF;

  SELECT * INTO v_command
  FROM public.match_commands
  WHERE game_id = p_game_id AND command_id = p_command_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'rejected', 'errorCode', 'command_not_started');
  END IF;

  IF v_command.actor_id <> p_actor_id OR v_command.expected_revision <> p_expected_revision THEN
    RETURN jsonb_build_object('status', 'rejected', 'errorCode', 'command_id_conflict');
  END IF;

  IF v_command.status = 'accepted' THEN
    RETURN v_command.result;
  ELSIF v_command.status = 'rejected' THEN
    RETURN jsonb_build_object('status', 'rejected', 'errorCode', v_command.error_code);
  END IF;

  IF v_match.revision <> p_expected_revision THEN
    UPDATE public.match_commands
    SET status = 'rejected', error_code = 'revision_conflict', completed_at = NOW()
    WHERE game_id = p_game_id AND command_id = p_command_id;

    RETURN jsonb_build_object(
      'status', 'rejected',
      'errorCode', 'revision_conflict',
      'currentRevision', v_match.revision
    );
  END IF;

  v_next_revision := p_expected_revision + 1;

  IF COALESCE(jsonb_typeof(p_new_canonical_state), 'null') <> 'object'
    OR COALESCE(jsonb_typeof(p_player_a_projection), 'null') <> 'object'
    OR COALESCE(jsonb_typeof(p_player_b_projection), 'null') <> 'object' THEN
    RAISE EXCEPTION 'State and projections must be JSON objects';
  END IF;

  IF COALESCE((p_new_canonical_state ->> 'revision')::BIGINT, -1) <> v_next_revision
    OR COALESCE((p_player_a_projection ->> 'revision')::BIGINT, -1) <> v_next_revision
    OR COALESCE((p_player_b_projection ->> 'revision')::BIGINT, -1) <> v_next_revision THEN
    RAISE EXCEPTION 'State and projection revisions must equal %', v_next_revision;
  END IF;

  IF COALESCE((p_new_canonical_state ->> 'schemaVersion')::INTEGER, -1) <> v_match.schema_version
    OR COALESCE((p_new_canonical_state ->> 'protocolVersion')::INTEGER, -1) <> v_match.protocol_version
    OR COALESCE((p_new_canonical_state ->> 'rulesetVersion')::INTEGER, -1) <> v_match.ruleset_version THEN
    RAISE EXCEPTION 'State version does not match the pinned match version';
  END IF;

  SELECT COALESCE(player_a_id, host_id), player_b_id
  INTO v_player_a_id, v_player_b_id
  FROM public.games
  WHERE id = p_game_id;

  IF v_player_a_id IS NULL OR v_player_b_id IS NULL THEN
    RAISE EXCEPTION 'Ranked match requires two assigned players';
  END IF;

  v_next_status := COALESCE(p_new_canonical_state #>> '{match,status}', v_match.status);
  IF v_next_status NOT IN ('setup', 'active', 'finished', 'cancelled') THEN
    RAISE EXCEPTION 'Invalid authoritative match status';
  END IF;

  UPDATE public.authoritative_matches
  SET revision = v_next_revision,
      status = v_next_status,
      canonical_state = p_new_canonical_state,
      result = COALESCE(p_result, result)
  WHERE game_id = p_game_id;

  INSERT INTO public.match_projections (
    game_id, viewer_id, viewer_role, revision, projection
  ) VALUES
    (p_game_id, v_player_a_id, 'playerA', v_next_revision, p_player_a_projection),
    (p_game_id, v_player_b_id, 'playerB', v_next_revision, p_player_b_projection)
  ON CONFLICT (game_id, viewer_id) DO UPDATE
  SET viewer_role = EXCLUDED.viewer_role,
      revision = EXCLUDED.revision,
      projection = EXCLUDED.projection;

  INSERT INTO public.match_outbox (game_id, revision, viewer_id, payload)
  VALUES
    (p_game_id, v_next_revision, v_player_a_id, p_player_a_projection),
    (p_game_id, v_next_revision, v_player_b_id, p_player_b_projection);

  v_actor_projection := CASE
    WHEN p_actor_id = v_player_a_id THEN p_player_a_projection
    WHEN p_actor_id = v_player_b_id THEN p_player_b_projection
    ELSE NULL
  END;

  IF v_actor_projection IS NULL THEN
    RAISE EXCEPTION 'Actor is not assigned to a ranked player slot';
  END IF;

  v_command_result := jsonb_build_object(
    'status', 'accepted',
    'revision', v_next_revision,
    'projection', v_actor_projection
  );

  UPDATE public.match_commands
  SET status = 'accepted',
      committed_revision = v_next_revision,
      result = v_command_result,
      completed_at = NOW()
  WHERE game_id = p_game_id AND command_id = p_command_id;

  RETURN v_command_result;
END;
$$;

