-- =====================================================
-- AUTHORITATIVE MULTIPLAYER V2 FOUNDATION (ADDITIVE)
-- =====================================================
-- This migration does not activate protocol v2 and does not revoke legacy
-- game_state writes. Canonical state and command processing remain isolated
-- until the server worker, shadow parity, and rollback gates are complete.

CREATE TABLE public.authoritative_matches (
  game_id UUID PRIMARY KEY REFERENCES public.games(id) ON DELETE CASCADE,
  player_a_id UUID NOT NULL REFERENCES public.profiles(id),
  player_b_id UUID NOT NULL REFERENCES public.profiles(id),
  schema_version INTEGER NOT NULL DEFAULT 1 CHECK (schema_version > 0),
  protocol_version INTEGER NOT NULL DEFAULT 2 CHECK (protocol_version > 0),
  ruleset_version INTEGER NOT NULL DEFAULT 1 CHECK (ruleset_version > 0),
  revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
  status TEXT NOT NULL DEFAULT 'setup'
    CHECK (status IN ('setup', 'active', 'finished', 'cancelled')),
  canonical_state JSONB NOT NULL CHECK (jsonb_typeof(canonical_state) = 'object'),
  result JSONB,
  started_at TIMESTAMPTZ,
  ends_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (ends_at IS NULL OR started_at IS NULL OR ends_at > started_at)
);

CREATE TABLE public.match_commands (
  game_id UUID NOT NULL REFERENCES public.authoritative_matches(game_id) ON DELETE CASCADE,
  command_id UUID NOT NULL,
  actor_id UUID NOT NULL REFERENCES public.profiles(id),
  expected_revision BIGINT NOT NULL CHECK (expected_revision >= 0),
  command_type TEXT NOT NULL
    CHECK (command_type IN ('place_piece', 'respond_to_check', 'mark_piece', 'resolve_nexus')),
  payload JSONB NOT NULL DEFAULT '{}'::JSONB CHECK (jsonb_typeof(payload) = 'object'),
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'accepted', 'rejected')),
  committed_revision BIGINT CHECK (committed_revision >= 0),
  result JSONB,
  error_code TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  PRIMARY KEY (game_id, command_id)
);

CREATE TABLE public.match_projections (
  game_id UUID NOT NULL REFERENCES public.authoritative_matches(game_id) ON DELETE CASCADE,
  viewer_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  viewer_role TEXT NOT NULL CHECK (viewer_role IN ('playerA', 'playerB')),
  revision BIGINT NOT NULL CHECK (revision >= 0),
  projection JSONB NOT NULL CHECK (jsonb_typeof(projection) = 'object'),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (game_id, viewer_id),
  UNIQUE (game_id, viewer_role)
);

CREATE TABLE public.match_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id UUID NOT NULL REFERENCES public.authoritative_matches(game_id) ON DELETE CASCADE,
  revision BIGINT NOT NULL CHECK (revision >= 0),
  viewer_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL DEFAULT 'match_projection',
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (game_id, revision, viewer_id, event_type)
);

CREATE INDEX idx_match_commands_pending
  ON public.match_commands (game_id, created_at)
  WHERE status = 'pending';

CREATE INDEX idx_match_outbox_unpublished
  ON public.match_outbox (next_attempt_at, id)
  WHERE published_at IS NULL;

ALTER TABLE public.authoritative_matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.match_commands ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.match_projections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.match_outbox ENABLE ROW LEVEL SECURITY;

-- Players can fetch only their already-sanitized projection. Canonical state,
-- commands, and outbox rows deliberately have no authenticated RLS policy.
CREATE POLICY "Players can view own authoritative projection"
  ON public.match_projections FOR SELECT
  TO authenticated
  USING (viewer_id = auth.uid());

-- Realtime Broadcast checks this policy when an authenticated client joins a
-- private per-viewer topic. No insert policy is granted, so clients cannot
-- publish authoritative projections themselves.
CREATE POLICY "Players receive own authoritative projection broadcasts"
  ON realtime.messages FOR SELECT
  TO authenticated
  USING (
    realtime.messages.extension = 'broadcast'
    AND realtime.messages.topic = realtime.topic()
    AND EXISTS (
      SELECT 1
      FROM public.match_projections projection
      WHERE projection.viewer_id = auth.uid()
        AND realtime.topic() = (
          'ranked-match:' || projection.game_id::TEXT ||
          ':viewer:' || projection.viewer_id::TEXT
        )
    )
  );

